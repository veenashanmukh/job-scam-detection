"""Render the data-quality report from run_pipeline() output. Contains no hard-coded dataset facts."""
from __future__ import annotations

MANUAL_ITEMS = [
    "Licence / terms of use: read the original source (Univ. of the Aegean EMSCAD page) and the Kaggle licence field. "
    "The script cannot check this.",
    "Contact fields: confirm by eye whether placeholder tokens replace emails/phones/URLs (see 'contact_patterns').",
    "Label definition: read Vidros et al., Future Internet 9(1):6 (2017), https://doi.org/10.3390/fi9010006.",
    "Skim 10 fraud and 10 legitimate postings, plus 10 flagged near-duplicate groups, to sanity-check the dedupe threshold.",
]


def _fmt(v, nd=2):
    if v is None:
        return "n/a"
    return f"{v:.{nd}f}" if isinstance(v, float) else str(v)


def gates(result: dict) -> list[tuple[str, str, str]]:
    """(gate, status, detail). PASS/FLAG are mechanical; they are not a judgement of research validity."""
    prof, dup = result["profile"], result["duplicates"]
    lc = prof["label_counts"]
    out = [
        ("Schema valid (required columns, unique ids, binary label)", "PASS", "validate_schema() did not raise"),
        ("Both classes present", "PASS" if 0 in lc and 1 in lc else "FAIL", f"label_counts={lc}"),
    ]
    fraud = lc.get(1, 0)
    out.append((
        "Fraud-class size (>= 100 postings for a 15% test split to hold >= ~15)",
        "PASS" if fraud >= 100 else "FLAG",
        f"{fraud} fraud postings; a 15% test split holds ~{round(fraud * 0.15)}. Plan for wide confidence intervals.",
    ))
    out.append((
        "No giant duplicate group (largest < 5% of rows)",
        "PASS" if dup["largest_group_pct_of_rows"] < 5 else "FLAG",
        f"largest group = {dup['largest_group_size']} rows ({_fmt(dup['largest_group_pct_of_rows'])}%)",
    ))
    out.append((
        "No duplicate groups with conflicting labels",
        "PASS" if dup["groups_with_conflicting_labels"] == 0 else "FLAG",
        f"{dup['groups_with_conflicting_labels']} groups (such groups are treated as fraud for stratification)",
    ))
    out.append(("Empty model text rows", "PASS" if prof["empty_text_rows"] == 0 else "FLAG", f"{prof['empty_text_rows']} rows"))
    if "leakage" in result:
        for name, c in result["leakage"]["checks"].items():
            out.append((f"Leakage: {name}", "PASS" if c["passed"] else "FAIL", str(c["details"])))
    out.append(("Licence verified", "MANUAL", "not checkable by script"))
    return out


def render_markdown(result: dict) -> str:
    p, d, s = result["profile"], result["duplicates"], result["schema"]
    L = ["# Data-Quality Report", "",
         f"Raw file: `{result['raw_file']}`  \nSHA-256: `{result['raw_sha256']}`", "",
         "Generated by `scripts/prepare_data.py`. Every number below is computed from the file above.", "",
         "## Gates", "", "| Gate | Status | Detail |", "|---|---|---|"]
    for g, st, det in gates(result):
        L.append(f"| {g} | **{st}** | {det} |")
    L += ["", "## Schema", "", f"{s['n_rows']} rows x {s['n_cols']} columns."]
    L += [f"- {w}" for w in s["warnings"]] or ["- No schema warnings."]
    L += ["", "## Labels", "", f"Counts: `{p['label_counts']}`; fraud rate {_fmt(p['fraud_rate'] * 100 if p['fraud_rate'] is not None else None)}%.",
          "", "## Missingness (percent of rows)", "", "| Field | Missing | % | % in fraud | % in legit |", "|---|---|---|---|---|"]
    for c, m in p["missingness"].items():
        L.append(f"| {c} | {m['missing']} | {_fmt(m['missing_pct'])} | {_fmt(m['missing_pct_in_fraud'])} | {_fmt(m['missing_pct_in_legit'])} |")
    L += ["", "## Text length (words in combined model text)", "", "| Class | mean | median | p90 | p99 | max |", "|---|---|---|---|---|---|"]
    for k, v in p["text_length_words"].items():
        if v:
            L.append(f"| {k} | {_fmt(v['mean'], 1)} | {_fmt(v['median'], 1)} | {_fmt(v['p90'], 1)} | {_fmt(v['p99'], 1)} | {v['max']} |")
    L += ["", f"{_fmt(p['pct_over_200_words'], 1)}% of postings exceed 200 words (rough proxy for a 256-token limit; measure real "
          f"token lengths in Phase 2). Rows with HTML tags in raw text: {p['html_tag_rows']}. Rows with empty model text: {p['empty_text_rows']}.",
          "", "## Contact information and redaction (pattern counts)", ""]
    cp = p["contact_patterns"]
    L += [f"- {k}: {v}" for k, v in cp.items() if k != "note"] + ["", f"_{cp['note']}_"]
    L += ["", "## Duplicates", "",
          f"Near-duplicate rule: cosine >= {d['near_threshold']} on word 1-2gram TF-IDF of normalised text; exact = identical normalised text.", "",
          f"- Groups: {d['n_groups']} for {d['n_rows']} rows",
          f"- Rows in multi-member groups: {d['rows_in_multi_member_groups']} (in {d['n_multi_member_groups']} groups)",
          f"- Exact duplicate rows beyond the first of their text: {d['exact_duplicate_rows_beyond_first']}",
          f"- Largest group: {d['largest_group_size']} rows ({_fmt(d['largest_group_pct_of_rows'])}%)",
          f"- Groups with conflicting labels: {d['groups_with_conflicting_labels']}",
          f"- Group size distribution: `{d['group_size_distribution']}`"]
    if "split" in result:
        L += ["", "## Shared split", "", f"Seed {result['manifest']['seed']}, fractions {result['manifest']['fractions']}. "
              "Group-aware, stratified on whether a group contains fraud.", "",
              "| Split | Rows | Fraud | Fraud rate | SHA-256 |", "|---|---|---|---|---|"]
        for name, i in result["split"].items():
            L.append(f"| {name} | {i['n_rows']} | {i['n_fraud']} | {_fmt(i['fraud_rate'] * 100 if i['fraud_rate'] is not None else None)}% | `{i['sha256'][:16]}...` |")
        L += ["", "### Leakage checks", "", "| Check | Passed |", "|---|---|"]
        for k, c in result["leakage"]["checks"].items():
            L.append(f"| {k} | {c['passed']} |")
        L += ["", f"Near-duplicate similarity across splits: `{result['leakage']['checks']['no_cross_split_near_duplicates']['details']}`"]
    L += ["", "## Manual verification still required", ""] + [f"- [ ] {m}" for m in MANUAL_ITEMS] + [""]
    return "\n".join(L)
